#!/usr/bin/env python3
"""
A tiny AnyConnect/OpenConnect-compatible test gateway.

SECURITY NOTE: this gateway is a *test-only* fixture. It speaks plain username/password
(plus optional TOTP) over a self-signed certificate and is meant to be run on localhost
while testing DeepConnect. Never expose it to untrusted networks and never reuse the
sample credentials or the test certificate secret for anything real.

It speaks just enough of the Cisco AnyConnect protocol for the openconnect client
library (and therefore the DeepConnect Android app) to:

  * negotiate TLS with a self-signed certificate (so the app's "untrusted certificate"
    dialog is exercised),
  * authenticate with a username/password form,
  * optionally validate a TOTP code generated by the client from a stored secret,
  * open a CSTP tunnel and exchange IP packets, answering ICMP echo requests so that
    `ping <gateway>` from the device proves the tunnel data path works.

Run:
    TOTP_SECRET=JBSWY3DPEHPK3PXP python3 anyconnect_mock.py 1443
"""

import base64
import hashlib
import hmac
import os
import re
import socket
import ssl
import struct
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

LISTEN_HOST = os.environ.get("VPN_BIND_HOST", "127.0.0.1")  # loopback only by design
LISTEN_PORT = int(sys.argv[1]) if len(sys.argv) > 1 else 1443
HERE = os.path.dirname(os.path.abspath(__file__))

# Directory containing server.crt / server.key (generated with openssl req -x509 ...).
CERT_DIR = os.environ.get("CERT_DIR", HERE)

USERNAME = os.environ.get("VPN_USER", "testuser")
PASSWORD = os.environ.get("VPN_PASS", "testpass")
TOTP_SECRET = os.environ.get("TOTP_SECRET", "").strip()          # base32, empty disables OTP
# Advertise a DTLS side channel but never answer on UDP. Reproduces the common
# "DTLS handshake failed: 2" fallback seen when a firewall/NAT drops UDP.
DROP_DTLS = os.environ.get("DROP_DTLS", "") == "1"

GW_ADDR = "192.168.88.1"
CLIENT_ADDR = "192.168.88.10"
NETMASK = "255.255.255.0"
MTU = "1400"

AC_PKT_DATA = 0
AC_PKT_DPD_OUT = 3
AC_PKT_DPD_RESP = 4
AC_PKT_DISCONN = 5
AC_PKT_KEEPALIVE = 7
AC_PKT_TERM_SERVER = 9

lock = threading.Lock()


def log(*args):
    with lock:
        print(time.strftime("[%H:%M:%S]"), *args, flush=True)


# --------------------------------------------------------------------------- #
# TOTP (RFC 6238, SHA-1, 6 digits, 30 s) — used to validate the code that the
# client library generated from the stored secret.
# --------------------------------------------------------------------------- #

def totp_codes(secret_b32, step=30, digits=6, window=1):
    secret = base64.b32decode(secret_b32.upper() + "=" * ((8 - len(secret_b32) % 8) % 8))
    counter = int(time.time()) // step
    codes = []
    for offset in range(-window, window + 1):
        msg = struct.pack(">Q", counter + offset)
        digest = hmac.new(secret, msg, hashlib.sha1).digest()
        ob = digest[-1] & 0x0F
        code = (struct.unpack(">I", digest[ob:ob + 4])[0] & 0x7FFFFFFF) % (10 ** digits)
        codes.append("%0*d" % (digits, code))
    return codes


def check_totp(code):
    if not TOTP_SECRET:
        return True
    try:
        valid = totp_codes(TOTP_SECRET)
    except Exception as exc:  # noqa: BLE001
        log("TOTP backend error:", exc)
        return False
    log("TOTP received", code, "expected one of", valid)
    return code in valid


