AUTH_REQUEST_XML = """<?xml version="1.0" encoding="UTF-8"?>
<config-auth client="vpn" type="auth-request" aggregate-auth-version="2">
  <version who="vpn">9.1.0</version>
  <auth id="main">
    <title>Login</title>
    <banner>DeepConnect test gateway</banner>
    <message>Enter your credentials</message>
    <form method="post">
      <input type="text" name="username" label="Username:"/>
      <input type="password" name="password" label="Password:"/>
      {secondary}
      <input type="submit" name="Login" value="Login"/>
    </form>
  </auth>
</config-auth>
"""

SECONDARY_INPUT = '<input type="password" name="secondary_password" label="Secondary Password:"/>'

AUTH_FAILED_XML = """<?xml version="1.0" encoding="UTF-8"?>
<config-auth client="vpn" type="auth-request" aggregate-auth-version="2">
  <auth id="main">
    <error>Login failed. Please try again.</error>
    <message>Enter your credentials</message>
    <form method="post">
      <input type="text" name="username" label="Username:"/>
      <input type="password" name="password" label="Password:"/>
      {secondary}
      <input type="submit" name="Login" value="Login"/>
    </form>
  </auth>
</config-auth>
"""

AUTH_COMPLETE_XML = """<?xml version="1.0" encoding="UTF-8"?>
<config-auth client="vpn" type="complete" aggregate-auth-version="2">
  <session-token>{token}</session-token>
  <session-id>deepconnect-test</session-id>
  <auth id="success">
    <banner>Welcome to the DeepConnect test gateway</banner>
    <message>Login successful</message>
  </auth>
</config-auth>
"""


def auth_form(failed=False):
    body = AUTH_FAILED_XML if failed else AUTH_REQUEST_XML
    return body.format(secondary=SECONDARY_INPUT if TOTP_SECRET else "").encode()


def extract(body, tag):
    m = re.search(r"<%s>\s*(.*?)\s*</%s>" % (tag, tag), body, re.S)
    return m.group(1) if m else ""


def parse_params(body, content_type):
    """Returns a dict of the auth parameters from either XML or urlencoded bodies."""
    params = {}
    if not body:
        return params
    text = body.decode("utf-8", "replace")
    if "<auth" in text or "<config-auth" in text:
        for tag in ("username", "password", "secondary_password", "group_list"):
            value = extract(text, tag)
            if value:
                params[tag] = value
        if not params:
            # self-closing style: <username>foo</username> handled above
            pass
    elif "application/x-www-form-urlencoded" in (content_type or ""):
        from urllib.parse import parse_qs
        for key, values in parse_qs(text).items():
            params[key] = values[0]
    return params


# --------------------------------------------------------------------------- #
# CSTP framing helpers
# --------------------------------------------------------------------------- #

def cstp_frame(ptype, payload=b""):
    return b"STF\x01" + struct.pack(">H", len(payload)) + bytes([ptype, 0]) + payload


def read_exact(stream, count):
    data = b""
    while len(data) < count:
        chunk = stream.read(count - len(data))
        if not chunk:
            raise ConnectionError("client closed the connection")
        data += chunk
    return data


def checksum(data):
    if len(data) % 2:
        data += b"\x00"
    total = 0
    for i in range(0, len(data), 2):
        total += (data[i] << 8) + data[i + 1]
    while total >> 16:
        total = (total & 0xFFFF) + (total >> 16)
    return (~total) & 0xFFFF


def icmp_echo_reply(packet):
    """Given an IPv4 packet containing an ICMP echo request, return an echo reply."""
    if len(packet) < 28:
        return None
    version_ihl = packet[0]
    if version_ihl >> 4 != 4:
        return None
    ihl = (version_ihl & 0x0F) * 4
    if len(packet) < ihl + 8:
        return None
    if packet[9] != 1:  # ICMP
        return None
    icmp = bytearray(packet[ihl:])
    if icmp[0] != 8:  # echo request
        return None
    icmp[0] = 0  # echo reply
    icmp[2] = icmp[3] = 0
    struct.pack_into(">H", icmp, 2, checksum(bytes(icmp)))
    total_len = ihl + len(icmp)
    src = packet[12:16]
    dst = packet[16:20]
    ip = bytearray(packet[:ihl])
    ip[0:2] = b"\x45\x00"
    struct.pack_into(">H", ip, 2, total_len)
    ip[10:12] = b"\x00\x00"
    ip[12:16] = dst
    ip[16:20] = src
    struct.pack_into(">H", ip, 10, checksum(bytes(ip)))
    return bytes(ip) + bytes(icmp)


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server_version = "DeepConnectTestGW/1.0"

    def log_message(self, fmt, *args):  # keep the console tidy
        log("http:", fmt % args)

    # -- helpers ----------------------------------------------------------- #
    def _read_body(self):
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0:
            return b""
        return self.rfile.read(length)

    def _send_xml(self, payload, status=200):
        self.send_response(status)
        self.send_header("Content-Type", "text/xml; charset=utf-8")
        self.send_header("Content-Length", str(len(payload)))
        self.send_header("Connection", "keep-alive")
        self.end_headers()
        self.wfile.write(payload)
        self.wfile.flush()

    def _handle_auth(self):
        body = self._read_body()
        params = parse_params(body, self.headers.get("Content-Type"))
        if not params:
            log("initial auth probe -> sending login form")
            self._send_xml(auth_form())
            return

        user = params.get("username", "")
        password = params.get("password", "")
        otp = params.get("secondary_password", "")
        log("auth attempt user=%r otp=%r" % (user, otp))

        if user != USERNAME or password != PASSWORD:
            log("authentication rejected (bad credentials)")
            self._send_xml(auth_form(failed=True))
            return
        if not check_totp(otp):
            log("authentication rejected (bad TOTP)")
            self._send_xml(auth_form(failed=True))
            return

        token = base64.b64encode(os.urandom(18)).decode()
        log("authentication accepted; issuing session token")
        self._send_xml(AUTH_COMPLETE_XML.format(token=token).encode())

    # -- HTTP verbs -------------------------------------------------------- #
    def do_GET(self):
        if self.path.startswith("/CSCOSSLC/tunnel"):
            self._send_xml(b"<error>use CONNECT</error>", status=400)
            return
        self._read_body()
        log("GET", self.path)
        self._send_xml(auth_form())

    def do_POST(self):
        if self.path.startswith("/CSCOSSLC/tunnel"):
            self._send_xml(b"<error>use CONNECT</error>", status=400)
            return
        log("POST", self.path)
        self._handle_auth()

    def _cstp_tunnel(self):
        cookie = self.headers.get("Cookie", "")
        if "webvpn=" not in cookie:
            log("CONNECT without a webvpn cookie -> 401")
            self.send_response(401)
            self.send_header("Connection", "close")
            self.send_header("Content-Length", "0")
            self.end_headers()
            self.close_connection = True
            return

        log("CSTP CONNECT accepted:", self.headers.get("X-CSTP-Address-Type"))
        headers = [
            "HTTP/1.1 200 CONNECTED",
            "X-CSTP-Version: 1",
            "X-CSTP-Address: %s" % CLIENT_ADDR,
            "X-CSTP-Netmask: %s" % NETMASK,
            "X-CSTP-DNS: %s" % GW_ADDR,
            "X-CSTP-MTU: %s" % MTU,
            "X-CSTP-Base-MTU: 1400",
            "X-CSTP-DPD: 30",
            "X-CSTP-Keepalive: 30",
            "X-CSTP-Idle-Timeout: 1800",
            "X-CSTP-Session-Timeout: 3600",
            "X-CSTP-CipherSuite: AES128-GCM",
            "X-CSTP-Default-Domain: test.local",
        ]
        if DROP_DTLS:
            headers += [
                "X-DTLS-Port: %d" % LISTEN_PORT,
                "X-DTLS-Session-ID: " + "ab" * 32,
                "X-DTLS-App-ID: " + "cd" * 32,
                "X-DTLS-CipherSuite: PSK-NEGOTIATE",
                "X-DTLS-DPD: 10",
                "X-DTLS-Keepalive: 32400",
            ]
        self.wfile.write(("\r\n".join(headers) + "\r\n\r\n").encode())
        self.wfile.flush()
        self.close_connection = True
        self._tunnel_loop()

    def _tunnel_loop(self):
        log("tunnel up: client %s gateway %s" % (CLIENT_ADDR, GW_ADDR))
        data_packets = 0
        try:
            while True:
                header = read_exact(self.rfile, 8)
                if header[:4] != b"STF\x01":
                    log("bad CSTP magic", header[:4])
                    break
                length = struct.unpack(">H", header[4:6])[0]
                ptype = header[6]
                payload = read_exact(self.rfile, length) if length else b""

                if ptype == AC_PKT_DATA:
                    data_packets += 1
                    if data_packets <= 5 or data_packets % 10 == 0:
                        proto = payload[9] if len(payload) > 9 else -1
                        log("data #%d %d bytes proto=%d %s -> %s" % (
                            data_packets, len(payload), proto,
                            ".".join(map(str, payload[12:16])),
                            ".".join(map(str, payload[16:20]))))
                    reply = icmp_echo_reply(payload)
                    if reply:
                        log("answering ICMP echo request with %d-byte reply" % len(reply))
                        self.wfile.write(cstp_frame(AC_PKT_DATA, reply))
                        self.wfile.flush()
                elif ptype == AC_PKT_DPD_OUT:
                    log("DPD request -> responding")
                    self.wfile.write(cstp_frame(AC_PKT_DPD_RESP))
                    self.wfile.flush()
                elif ptype == AC_PKT_KEEPALIVE:
                    pass
                elif ptype == AC_PKT_DISCONN:
                    log("client sent disconnect")
                    break
                else:
                    log("packet type %d len %d (ignored)" % (ptype, length))
        except (ConnectionError, ssl.SSLError, OSError) as exc:
            log("tunnel closed:", exc)
        log("tunnel down after %d data packets" % data_packets)

    def do_CONNECT(self):
        log("CONNECT", self.path)
        self._cstp_tunnel()


class ThreadingTLSServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True


def main():
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.load_cert_chain(os.path.join(CERT_DIR, "server.crt"), os.path.join(CERT_DIR, "server.key"))
    context.minimum_version = ssl.TLSVersion.TLSv1_2
    httpd = ThreadingTLSServer((LISTEN_HOST, LISTEN_PORT), Handler)
    httpd.socket = context.wrap_socket(httpd.socket, server_side=True)
    log("AnyConnect test gateway listening on https://%s:%d" % (LISTEN_HOST, LISTEN_PORT))
    log("user=%s password=%s totp=%s" % (USERNAME, PASSWORD, TOTP_SECRET or "disabled"))
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
